from datetime import date, datetime
from typing import Protocol

from roostr.domain.models import ExecutionRecord, Job


class ExecutionTargetPort(Protocol):
    def launch(self, job: Job, dt: datetime) -> tuple[bool, str]:
        """Launch the job in the target environment (Terminal, Herdr, or Background)."""
        ...


class JobRepositoryPort(Protocol):
    def save_job(self, job: Job) -> None: ...
    def get_job(self, job_id: str) -> Job | None: ...
    def list_jobs(self) -> list[Job]: ...
    def delete_job(self, job_id: str) -> None: ...
    def set_paused(self, job_id: str, paused: bool) -> None: ...
    def record_execution(self, record: ExecutionRecord) -> None: ...
    def count_executions(self, job_id: str) -> int: ...
    def get_last_execution(self, job_id: str) -> ExecutionRecord | None: ...
    def get_recent_executions(self, job_id: str, limit: int = 5) -> list[ExecutionRecord]: ...
    def has_succeeded_on_date(self, job_id: str, target_date: date) -> bool: ...


class SchedulerPort(Protocol):
    def install(self, job: Job) -> None: ...
    def uninstall(self, job_id: str) -> None: ...
    def pause(self, job_id: str) -> None: ...
    def resume(self, job: Job) -> None: ...


class NotificationPort(Protocol):
    def notify(self, title: str, message: str) -> None: ...
